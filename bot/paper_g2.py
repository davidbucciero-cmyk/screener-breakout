"""Execution quotidienne du paper trading G2 (3 enveloppes de 10 000 $ : vol 19 %, 25 %, 40 %).

Chaque jour a 00:10 UTC, apres la cloture quotidienne :
  1. clotures Binance ; aucun ordre si elles sont perimees ;
  2. limites de risque par enveloppe (kill switch, perte du jour, sans levier) ;
  3. decision (meme fonction que le backtest), ordres nets par crypto sur Alpaca paper ;
  4. ordre > 5 000 $ : issue GitHub, execute seulement apres le label `approved` ;
  5. etat, journal et email (ordres, alertes ; resume chaque lundi).
Remettre une enveloppe en route apres un kill switch : passer `halted` a false dans paper_g2/state.json.
"""
